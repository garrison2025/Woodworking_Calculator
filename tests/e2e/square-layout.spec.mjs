import {test,expect} from "@playwright/test";
import {readFileSync} from "node:fs";

test("square check rejects equal-but-wrong diagonals and keeps target-only aspect-correct diagram",async({page})=>{
  await page.goto("/square-layout-calculator/");
  await expect(page.locator("#calc-error")).toBeHidden();
  const ideal=page.locator("#result-cards .metric").filter({hasText:"Ideal right-angle diagonal"});
  const count=page.locator("#result-cards .metric").filter({hasText:"Numeric checks within tolerance"});
  await expect(ideal).toContainText("60 in");
  await expect(count).toContainText("3");
  await expect(page.locator("#cut-table tbody tr")).toHaveCount(3);
  const rect=page.locator("#dimension-svg svg .square-target-outline");
  const diagA=page.locator("#dimension-svg svg .square-target-a");
  const diagB=page.locator("#dimension-svg svg .square-target-b");
  await expect(rect).toHaveCount(1);
  await expect(diagA).toHaveCount(1);
  await expect(diagB).toHaveCount(1);
  const rw=Number(await rect.getAttribute("width"));
  const rh=Number(await rect.getAttribute("height"));
  expect(rw/rh).toBeCloseTo(36/48,8);
  await page.locator("#f-measuredA").fill("65");
  await page.locator("#f-measuredB").fill("65");
  await expect(count).toContainText("1");
  await expect(page.locator("#result-cards .metric").filter({hasText:"Difference between measured diagonals"})).toContainText("0 in");
  await expect(page.locator("#result-cards .metric").filter({hasText:"Maximum absolute diagonal target error"})).toContainText("5 in");
  const cells=page.locator("#cut-table tbody tr");
  await expect(cells.nth(0)).toContainText("Outside stated tolerance");
  await expect(cells.nth(1)).toContainText("Outside stated tolerance");
  await expect(cells.nth(2)).toContainText("Within stated tolerance");
  expect(Number(await rect.getAttribute("width"))).toBeCloseTo(rw,8);
  expect(Number(await rect.getAttribute("height"))).toBeCloseTo(rh,8);
  await page.locator("#f-measuredA").fill("59.875");
  await page.locator("#f-measuredB").fill("60");
  await expect(count).toContainText("3");
  await expect(cells.nth(0)).toContainText("Within stated tolerance");
  await page.locator("#unit-select").selectOption("mm");
  await expect(page.locator("#cut-table thead")).toContainText("Target Diagonal (mm)");
  await expect(page.locator("#cut-table thead")).toContainText("Measured Diagonal (mm)");
  await expect(page.locator("#cut-table thead")).toContainText("Check Result");
  const wait=page.waitForEvent("download");
  await page.locator("#download-csv").click();
  const csv=readFileSync(await (await wait).path(),"utf8");
  expect(csv).toContain('"Target Diagonal (mm)","Measured Diagonal (mm)","Signed Error (mm)"');
  expect(csv).toContain('"A vs B spread"');
  expect(csv).toContain('"Within stated tolerance"');
  await page.locator("#f-tolerance").fill("-1");
  await expect(page.locator("#calc-error")).toBeVisible();
  await expect(page.locator("#dimension-svg svg .square-target-outline")).toHaveCount(0);
  await expect(page.locator("#cut-table tbody tr")).toHaveCount(0);
});

test("diagonal numeric tolerance of zero is permitted without claiming angle certification",async({page})=>{
  await page.goto("/square-layout-calculator/");
  await page.locator("#f-tolerance").fill("0");
  await expect(page.locator("#calc-error")).toBeHidden();
  await expect(page.locator("#result-cards .metric").filter({hasText:"Numeric checks within tolerance"})).toContainText("3");
  const pageBody=await page.locator("main").innerText();
  expect(pageBody).toContain("Equal diagonals alone");
  expect(pageBody).toContain("IDEAL");
});
