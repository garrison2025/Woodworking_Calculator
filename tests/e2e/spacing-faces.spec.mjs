import {test,expect} from "@playwright/test";
import {readFileSync} from "node:fs";

test("deck final rip, board gaps and SVG drawing share CSV face coordinates",async({page})=>{
  await page.goto("/deck-board-calculator/");
  await expect(page.locator("#calc-error")).toBeHidden();
  const faces=page.locator("#dimension-svg svg .deck-board-face");
  await expect(faces).toHaveCount(22);
  const first=faces.first(),last=faces.last(),outline=page.locator("#dimension-svg svg .deck-face-outline");
  const firstWidth=Number(await first.getAttribute("width"));
  const lastWidth=Number(await last.getAttribute("width"));
  expect(lastWidth/firstWidth).toBeCloseTo(1.875/5.5,7);
  const ox=Number(await outline.getAttribute("x")), ow=Number(await outline.getAttribute("width"));
  const end=Number(await last.getAttribute("x"))+lastWidth;
  expect(end).toBeCloseTo(ox+ow,7);
  const second=faces.nth(1);
  const gap=Number(await second.getAttribute("x"))-Number(await first.getAttribute("x"))-firstWidth;
  expect(gap/ow).toBeCloseTo(.125/120,7);
  await expect(page.locator("#result-cards .metric").filter({hasText:"Covered deck width"})).toContainText("120 in");
  await expect(page.locator("#result-cards .metric").filter({hasText:"Stock pieces per row"})).toContainText("1");
  await expect(page.locator("#cut-table thead")).toContainText("Right (in)");
  await expect(page.locator("#cut-table thead")).toContainText("Gap After (in)");
  await expect(page.locator("#cut-table tbody tr").last()).toContainText("1.875 in");
  await page.locator("#f-stock").fill("100");
  await expect(page.locator("#result-cards .metric").filter({hasText:"Stock pieces per row"})).toContainText("2");
  await expect(page.locator("#result-cards .metric").filter({hasText:"Stock pieces: no offcut reuse"})).toContainText("49");
  await page.locator("#unit-select").selectOption("mm");
  await expect(page.locator("#cut-table thead")).toContainText("Right (mm)");
  const dl=page.waitForEvent("download");
  await page.locator("#download-csv").click();
  const csv=readFileSync(await (await dl).path(),"utf8");
  expect(csv).toContain('"Position (mm)","Left (mm)","Right (mm)","Length (mm)","Rip Width (mm)","Gap After (mm)"');
  expect(csv).toContain('"Row 22"');
  await page.locator("#unit-select").selectOption("in");
  await page.locator("#f-width").fill("5.62500005");
  await expect(page.locator("#calc-error")).toBeVisible();
  await expect(faces).toHaveCount(0);
});

test("baluster physical SVG faces conserve equal end gaps and printable CSV edges",async({page})=>{
  await page.goto("/baluster-spacing-calculator/");
  const faces=page.locator("#dimension-svg svg .baluster-face");
  await expect(faces).toHaveCount(17);
  await expect(page.locator("#result-cards .metric").filter({hasText:"Opening closure width"})).toContainText("96 in");
  await expect(page.locator("#result-cards .metric").filter({hasText:"Total baluster face width"})).toContainText("25.5 in");
  await expect(page.locator("#result-cards .metric").filter({hasText:"Total clear spaces"})).toContainText("70.5 in");
  const first=faces.first(),last=faces.last();
  const left=74,right=850,W=right-left;
  const x=Number(await first.getAttribute("x")),firstW=Number(await first.getAttribute("width"));
  expect(firstW/W).toBeCloseTo(1.5/96,7);
  const gap=(96-17*1.5)/18;
  expect((x-left)/W).toBeCloseTo(gap/96,7);
  expect((right-Number(await last.getAttribute("x"))-Number(await last.getAttribute("width")))/W).toBeCloseTo(gap/96,7);
  await expect(page.locator("#cut-table thead")).toContainText("Face Left (in)");
  await expect(page.locator("#cut-table thead")).toContainText("Face Right (in)");
  await page.locator("#f-width").fill("2");
  await expect(page.locator("#calc-error")).toBeHidden();
  await expect(faces).toHaveCount(16);
  await page.locator("#unit-select").selectOption("mm");
  await expect(page.locator("#cut-table thead")).toContainText("Clear Gap To Next (mm)");
  const dl=page.waitForEvent("download");
  await page.locator("#download-csv").click();
  const csv=readFileSync(await (await dl).path(),"utf8");
  expect(csv).toContain('"Face Left (mm)","Face Right (mm)","Clear Gap (mm)","Clear Gap To Next (mm)"');
  await page.locator("#f-width").fill("500");
  await expect(page.locator("#calc-error")).toBeVisible();
  await expect(faces).toHaveCount(0);
});

test("fence post end faces occupy whole outer span while center values remain signed",async({page})=>{
  await page.goto("/fence-post-calculator/");
  const faces=page.locator("#dimension-svg svg .post-face");
  await expect(faces).toHaveCount(14);
  await expect(page.locator("#result-cards .metric").filter({hasText:"Outside-to-outside fence length"})).toContainText("1,203.5 in");
  const first=faces.first(),last=faces.last();
  expect(Number(await first.getAttribute("x"))).toBeCloseTo(74,6);
  const lastEnd=Number(await last.getAttribute("x"))+Number(await last.getAttribute("width"));
  expect(lastEnd).toBeCloseTo(850,6);
  await expect(page.locator("#cut-table tbody tr").first()).toContainText("-1.75 in");
  await expect(page.locator("#cut-table tbody tr").last()).toContainText("1,201.75 in");
  await expect(page.locator("#cut-table thead")).toContainText("Face Left (in)");
  await page.locator("#f-length").fill("120");
  await page.locator("#f-bay").fill("24");
  await page.locator("#f-post").fill("23.5");
  await expect(page.locator("#calc-error")).toBeHidden();
  await expect(faces).toHaveCount(6);
  await expect(page.locator("#result-cards .metric").filter({hasText:"Outside-to-outside fence length"})).toContainText("143.5 in");
  await expect(page.locator("#result-cards .metric").filter({hasText:"Approximate clear bay"})).toContainText("0.5 in");
  const fwidth=Number(await faces.first().getAttribute("width"));
  expect(fwidth/(850-74)).toBeCloseTo(23.5/143.5,7);
  await page.locator("#unit-select").selectOption("mm");
  const dl=page.waitForEvent("download");
  await page.locator("#download-csv").click();
  const csv=readFileSync(await (await dl).path(),"utf8");
  expect(csv).toContain('"Center (mm)","Face Left (mm)","Face Right (mm)","Clear Bay To Next (mm)"');
  expect(csv).toContain('"Post 1","0","-298.45","298.45","12.7"');
  await page.locator("#f-post").fill("609.6");
  await expect(page.locator("#calc-error")).toBeVisible();
  await expect(faces).toHaveCount(0);
});
