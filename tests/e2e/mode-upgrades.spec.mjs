import {test,expect} from "@playwright/test";
import {readFileSync} from "node:fs";
test("roof pitch angle/rise modes show correct references and CSV numerical values",async({page})=>{
 await page.goto("/roof-pitch-calculator/");
 await expect(page.locator("#f-angle").locator("xpath=..")).toBeHidden();
 await page.locator("#f-roofMode").selectOption("1");
 await expect(page.locator("#f-angle").locator("xpath=..")).toBeVisible();
 await expect(page.locator("#f-pitch").locator("xpath=..")).toBeHidden();
 await page.locator("#f-angle").fill("45");
 await expect(page.locator("#result-cards .metric").filter({hasText:"Pitch / 12"})).toContainText("12:12");
 const a=page.locator("#dimension-svg svg .roof-pitch-slope");
 const slope=async()=>{const [x1,x2,y1,y2]=await Promise.all(["x1","x2","y1","y2"].map(k=>a.getAttribute(k).then(Number)));return Math.abs((y2-y1)/(x2-x1))};
 expect(await slope()).toBeCloseTo(1,8);
 await page.locator("#f-roofMode").selectOption("3");
 await page.locator("#f-measuredRise").fill("30");
 expect(await slope()).toBeCloseTo(.25,8);
 await page.locator("#unit-select").selectOption("mm");
 await expect(page.locator("#f-measuredRise")).toHaveValue("762");
 const ready=page.waitForEvent("download");
 await page.locator("#download-csv").click();
 const csv=readFileSync(await(await ready).path(),"utf8");
 expect(csv).toContain('"Pitch / 12","3","rise per 12 run"');
});
test("spacing count from maximum face gap and target interval retains exact polygon face bounds",async({page})=>{
 await page.goto("/equal-spacing-calculator/");
 await page.locator("#unit-select").selectOption("mm");
 await page.locator("#f-length").fill("1000");
 await page.locator("#f-left").fill("50");
 await page.locator("#f-right").fill("50");
 await page.locator("#f-itemWidth").fill("30");
 await page.locator("#f-spacingMode").selectOption("1");
 await page.locator("#f-maxClearGap").fill("150");
 await expect(page.locator("#dimension-svg svg .equal-part-face")).toHaveCount(6);
 await expect(page.locator("#result-cards .metric").filter({hasText:"Equal center interval"})).toContainText("180 mm");
 await page.locator("#f-maxClearGap").fill("130");
 await expect(page.locator("#dimension-svg svg .equal-part-face")).toHaveCount(7);
 await page.locator("#f-spacingMode").selectOption("2");
 await page.locator("#f-targetPitch").fill("180");
 await expect(page.locator("#dimension-svg svg .equal-part-face")).toHaveCount(6);
 await expect(page.locator("#result-cards .metric").filter({hasText:"Difference from target interval"})).toContainText("0 mm");
});
test("deck stair mode rejects undersized boards and flight that exceeds available run",async({page})=>{
 await page.goto("/stair-calculator/");
 await page.locator("#f-stairMode").selectOption("1");
 await expect(page.locator("#result-cards .metric").filter({hasText:"Deck tread board coverage"})).toContainText("11.125 in");
 await page.locator("#f-availableRun").fill("120");
 await expect(page.locator("#calc-error")).toBeVisible();
 await expect(page.locator("#dimension-svg svg")).toHaveCount(0);
 await page.locator("#f-availableRun").fill("140");
 await expect(page.locator("#calc-error")).toBeHidden();
 await page.locator("#f-deckBoardWidth").fill("3");
 await expect(page.locator("#calc-error")).toBeVisible();
 await page.locator("#f-deckBoardWidth").fill("5.5");
 await expect(page.locator("#calc-error")).toBeHidden();
 await page.locator("#f-stairMode").selectOption("0");
 await expect(page.locator("#f-deckBoardWidth").locator("xpath=..")).toBeHidden();
 await expect(page.locator("#result-cards .metric").filter({hasText:"Deck tread board coverage"})).toHaveCount(0);
});